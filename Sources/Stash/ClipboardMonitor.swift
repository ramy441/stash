import AppKit

/// Watches the system pasteboard and records text clips.
///
/// macOS publishes no change notification for the pasteboard, so polling `changeCount`
/// is the only option. It is an integer read against a running server, which is why
/// half a second costs nothing measurable.
@MainActor
final class ClipboardMonitor {
    /// Types that mean "do not persist this" by the community convention every serious
    /// password manager follows. Recording a concealed clip would defeat the whole app.
    private static let excludedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    /// A clip longer than this is something like a whole file pasted as text; storing it
    /// bloats the log for a row nobody can read anyway.
    static let maxLength = 32_000

    private let pasteboard = NSPasteboard.general
    private var timer: Timer?
    private var lastChangeCount: Int
    private var lastRecorded: String?

    init() {
        lastChangeCount = NSPasteboard.general.changeCount
        lastRecorded = HistoryStore.load().first?.text
    }

    func start() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        // .common so polling survives menu tracking — the pasteboard changes while a menu is open
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        Diagnostics.log("monitor started")
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Our own click-to-copy bumps changeCount; without this the clip we just served
    /// would come straight back in as a new record.
    func ignoreCurrentChange() {
        lastChangeCount = pasteboard.changeCount
        lastRecorded = pasteboard.string(forType: .string)
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        if let types = pasteboard.types, !Self.excludedTypes.isDisjoint(with: types) {
            Diagnostics.log("skipped concealed clip")
            return
        }
        guard let text = pasteboard.string(forType: .string) else { return }
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        guard text.count <= Self.maxLength else {
            Diagnostics.log("skipped oversized clip (\(text.count) chars)")
            return
        }
        guard text != lastRecorded else { return }

        lastRecorded = text
        let source = NSWorkspace.shared.frontmostApplication?.localizedName ?? "Unknown"
        HistoryStore.append(text, source: source)
    }
}
